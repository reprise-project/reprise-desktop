pub fn names() -> impl Iterator<Item = &'static str> {
    SCHEMES.iter().map(|(n, _)| *n)
}

pub fn scheme(name: &str) -> Option<ColorScheme> {
    SCHEMES
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, c)| c.clone())
}

pub fn name_of(cs: &ColorScheme) -> Option<&'static str> {
    SCHEMES.iter().find(|(_, c)| c == cs).map(|(n, _)| *n)
}

